# ==========================================
# OOPS (Object-Oriented Programming System)
# ==========================================

# OOPS is a programming concept that organizes code using
# Classes and Objects.

# It helps make programs:
# 1. Reusable
# 2. Secure
# 3. Easy to maintain
# 4. Easy to understand
# 5. Scalable for large projects

# ==========================================
# MAIN OOPS CONCEPTS
# ==========================================

# 1. Class         -> Blueprint for creating objects.
# 2. Object        -> Real-world instance of a class.
# 3. Encapsulation -> Hides data and protects it.
# 4. Inheritance   -> Reuses properties and methods from another class.
# 5. Polymorphism  -> Same method behaves differently for different objects.
# 6. Abstraction   -> Shows only essential details and hides implementation.

# ==========================================
# APPLICATIONS OF OOPS
# ==========================================

# OOPS is used in:
# - Banking Systems
# - Hospital Management Systems
# - E-commerce Applications
# - School/College Management Systems
# - Library Management Systems
# - Game Development
# - Mobile Applications
# - Desktop Software
# - Web Applications
# - AI and Machine Learning Projects