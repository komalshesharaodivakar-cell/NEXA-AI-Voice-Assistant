# Class
# -----
# A class is a blueprint or template.
# It defines what data (attributes) and actions (methods)
# an object will have.

# Constructor
# -----------
# A special method named __init__().
# It runs automatically whenever an object is created.
# It initializes (gives values to) the object's attributes.

# Attributes
# ----------
# Variables that belong to an object.
# They store information.
# Example:
# self.name
# self.price
# self.weight

# Method
# ------
# A function inside a class.
# It performs some action.
# Example:
# display_info()
# shipping_cost()

# Object
# ------
# A real instance created from a class.
# Example:
# laptop = Shipping(...)
# television = Shipping(...)